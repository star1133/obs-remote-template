export function icon(name, cls = "") {
  const svg = document.createElementNS(NS, "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("class", "ic" + (cls ? " " + cls : ""));
  svg.setAttribute("aria-hidden", "true");
  svg.dataset.name = name;
  for (const s of ICONS[name] ?? []) {
    const o = typeof s === "string" ? { d: s } : s;
    const p = document.createElementNS(NS, "path");
    p.setAttribute("d", o.d);
    p.setAttribute("pathLength", "1"); // lets CSS draw any stroke on with dash tricks
    if (o.cls) p.setAttribute("class", o.cls);
    svg.append(p);
  }
  return svg;
}

/** Fill every `[data-icon]` element with its icon (prepended, so text labels stay after it). */
export function hydrate(root = document) {
  for (const el of root.querySelectorAll("[data-icon]")) {
    el.prepend(icon(el.dataset.icon));
    el.removeAttribute("data-icon");
  }
}

/** Icon for a source row in the Sources list (what kind of thing it is, like OBS shows). */
export function sourceIcon(kind = "") {
  if (/dshow|v4l2|av_capture|camera/.test(kind)) return "camera";
  if (/window_capture/.test(kind)) return "window";
  if (/monitor|display|screen|game_capture/.test(kind)) return "desktop";
  if (/image|slideshow/.test(kind)) return "image";
  if (/text|freetype/.test(kind)) return "text";
  if (/browser/.test(kind)) return "globe";
  if (/ffmpeg|vlc|media/.test(kind)) return "music";
  if (/scene|group/.test(kind)) return "scenes";
  if (/capture/.test(kind)) return "speaker";
  return "sources";
}

/** Pick an icon for an OBS input kind. */
export function kindIcon(kind = "") {
  if (/process/.test(kind)) return "game";
  if (/input_capture/.test(kind)) return "mic";
  if (/output_capture/.test(kind)) return "speaker";
  if (/ffmpeg|media|vlc/.test(kind)) return "music";
  if (/browser/.test(kind)) return "globe";
  return "speaker";
}
